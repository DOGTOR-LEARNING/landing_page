// Uses a running local preview and an isolated test employee. Never prints tokens.
import assert from 'node:assert/strict'
const origin = process.env.ADMIN_TEST_ORIGIN || 'http://127.0.0.1:3000'
assert.match(origin, /^http:\/\/(127\.0\.0\.1|localhost)(:\d+)?$/, 'gateway checks are local-only')
const request = (path, options) => fetch(origin + path, options)
let response = await request('/api/admin/auth/login', { method: 'POST', headers: { Origin: 'https://evil.example', 'Content-Type': 'application/json' }, body: '{}' })
assert.equal(response.status, 403)
response = await request('/api/admin/auth/login', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{}' })
assert.equal(response.status, 403)
for (const path of ['/api/admin/users', '/api/admin/announcements', '/api/admin/announcements/admin/all']) assert.equal((await request(path)).status, 401)
response = await request('/api/admin/auth/login', { method: 'POST', headers: { Origin: origin, 'Content-Type': 'application/json' }, body: JSON.stringify({ email: 'owner@example.com', password: 'strong-owner-password' }) })
assert.equal(response.status, 200)
const cookie = response.headers.get('set-cookie')
assert.match(cookie, /HttpOnly/i)
assert.match(cookie, /SameSite=strict/i)
const data = await response.json()
assert.equal(data.session_token, undefined)
assert.equal(data.data.password_hash, undefined)
const sessionCookie = cookie.split(';')[0]
response = await request('/api/admin/auth/me', { headers: { Cookie: sessionCookie } })
assert.equal(response.status, 200)
response = await request('/api/admin/auth/change-password', { method: 'POST', headers: { Origin: origin, 'Content-Type': 'application/json', Cookie: sessionCookie }, body: JSON.stringify({ current_password: 'incorrect', password: 'another-strong-password' }) })
assert.equal(response.status, 400)
assert.equal(response.headers.get('set-cookie'), null, 'failed password change must keep login')
response = await request('/api/admin/auth/logout', { method: 'POST', headers: { Origin: origin, Cookie: sessionCookie } })
assert.equal(response.status, 200)
assert.match(response.headers.get('set-cookie'), /Max-Age=0/)
assert.equal((await request('/api/admin/auth/me', { headers: { Cookie: sessionCookie } })).status, 401)
console.log('Admin gateway checks passed: Origin/CSRF, old key removed, cookie flags, no token exposure, session/logout, failed password change.')
